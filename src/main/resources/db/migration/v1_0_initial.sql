-- Schéma initial. Scripts réexécutables pour le laboratoire H2.
CREATE TABLE IF NOT EXISTS utilisateurs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL,
  nom VARCHAR(255) NOT NULL,
  version INTEGER NOT NULL,
  CONSTRAINT uk_utilisateurs_email UNIQUE (email)
);
CREATE TABLE IF NOT EXISTS salles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(255) NOT NULL,
  capacite INTEGER NOT NULL,
  version INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS reservations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  salle_id BIGINT NOT NULL,
  utilisateur_id BIGINT NOT NULL,
  date_debut TIMESTAMP NOT NULL,
  date_fin TIMESTAMP NOT NULL,
  version INTEGER NOT NULL,
  CONSTRAINT fk_reservation_salle FOREIGN KEY (salle_id) REFERENCES salles(id),
  CONSTRAINT fk_reservation_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs(id),
  CONSTRAINT ck_reservation_duree CHECK (date_fin > date_debut)
);
CREATE INDEX IF NOT EXISTS idx_reservation_salle_dates ON reservations(salle_id, date_debut, date_fin);
